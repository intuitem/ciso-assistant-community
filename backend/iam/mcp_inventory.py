# the MCP server learns what a token may do
SERVER_OPERATIONS = {("GET", "mcp-access"): READ}
OPERATIONS.update(SERVER_OPERATIONS)

READ_COLLECTIONS = {
    name.removesuffix("-list")
    for (method, name), effect in OPERATIONS.items()
    if method == "GET" and name.endswith("-list")
}

# count_objects breaks a count down by any field of a collection it reads
_FIELD_CHOICES = re.compile(r"Get \w+ choices")


def _is_field_choices(method, match) -> bool:
    kwargs = getattr(match.func, "initkwargs", {})
    return (
        method == "GET"
        and kwargs.get("detail") is False
        and kwargs.get("basename") in READ_COLLECTIONS
        and bool(_FIELD_CHOICES.fullmatch(kwargs.get("name") or ""))
    )


def is_inventoried(method, match) -> bool:
    return (method, match.url_name) in OPERATIONS or _is_field_choices(method, match)

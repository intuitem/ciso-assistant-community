"""
Regression tests for the shipped MITRE ATT&CK TTP libraries.

The three domain libraries are generated by
`tools/excel/mitre/tools/mitre-attack_framework_builder.py`. These tests pin
the properties a regeneration must not break:

- every domain loads and produces its catalog, tactics in matrix column order,
  techniques, sub-technique parents and facet groups
- the domains coexist: `ReferenceControl` enforces a unique (ref_id, name) pair
  per folder, and ATT&CK publishes Mobile M1013 as a verbatim copy of
  Enterprise M1013, so Mobile must reference it rather than redeclare it
"""

from pathlib import Path

import pytest
import yaml
from django.db import models

from core.models import LoadedLibrary, ReferenceControl, StoredLibrary
from sec_intel.models import Tactic, Technique, TTPCatalog

LIBRARIES_DIR = Path(__file__).resolve().parents[2] / "library" / "libraries"

ENTERPRISE = "mitre-attack"
ICS = "mitre-attack-ics"
MOBILE = "mitre-attack-mobile"

# first four columns of each published matrix
EXPECTED_FIRST_TACTICS = {
    ICS: ["TA0108", "TA0104", "TA0110", "TA0111"],
    MOBILE: ["TA0027", "TA0041", "TA0028", "TA0029"],
}


def load_library(ref_id: str) -> LoadedLibrary:
    urn = f"urn:intuitem:risk:library:{ref_id}"
    loaded = LoadedLibrary.objects.filter(urn=urn).first()
    if loaded is not None:
        return loaded

    stored = StoredLibrary.objects.filter(urn=urn).first()
    if stored is None:
        content = (LIBRARIES_DIR / f"{ref_id}.yaml").read_bytes()
        stored, error = StoredLibrary.store_library_content(content)
        assert error is None, f"could not store {ref_id}: {error}"

    error = stored.load()
    assert error is None, f"could not load {ref_id}: {error}"
    return LoadedLibrary.objects.get(urn=urn)


def read_library(ref_id: str) -> dict:
    with (LIBRARIES_DIR / f"{ref_id}.yaml").open(encoding="utf-8") as stream:
        return yaml.safe_load(stream)


@pytest.mark.django_db
@pytest.mark.parametrize("ref_id", [ICS, MOBILE])
def test_domain_library_loads_with_a_complete_catalog(ref_id):
    load_library(ref_id)

    catalog = TTPCatalog.objects.get(urn=f"urn:intuitem:risk:ttp_catalog:{ref_id}")
    tactics = Tactic.objects.filter(catalog=catalog)
    techniques = Technique.objects.filter(catalog=catalog)

    assert tactics.count() == 12
    assert techniques.count() > 0
    assert techniques.filter(parent__isnull=False).exists()
    assert catalog.grouping_definition, "the catalog must expose facets"
    assert {entry["dimension"] for entry in catalog.grouping_definition} == {
        "asset" if ref_id == ICS else "platform"
    }

    # every technique belongs to at least one tactic of its own catalog
    for technique in techniques.prefetch_related("tactics"):
        linked = list(technique.tactics.all())
        assert linked, f"{technique.ref_id} has no tactic"
        for tactic in linked:
            assert tactic.catalog_id == catalog.id


@pytest.mark.django_db
@pytest.mark.parametrize("ref_id", [ICS, MOBILE])
def test_tactics_keep_the_published_matrix_order(ref_id):
    load_library(ref_id)

    catalog = TTPCatalog.objects.get(urn=f"urn:intuitem:risk:ttp_catalog:{ref_id}")
    ordered = [
        tactic.ref_id
        for tactic in Tactic.objects.filter(catalog=catalog).order_by("order_id")
    ]

    assert ordered[:4] == EXPECTED_FIRST_TACTICS[ref_id]
    # ref_id order is not column order, which is the whole point of order_id
    assert ordered != sorted(ordered)


@pytest.mark.django_db
def test_attack_domains_coexist():
    """All three domains must be loadable side by side in the same folder."""
    for ref_id in (ENTERPRISE, ICS, MOBILE):
        load_library(ref_id)

    assert TTPCatalog.objects.count() >= 3

    duplicates = (
        ReferenceControl.objects.values("folder", "ref_id", "name")
        .annotate(total=models.Count("id"))
        .filter(total__gt=1)
    )
    assert not list(duplicates)


@pytest.mark.django_db
def test_mobile_references_the_enterprise_copy_of_m1013():
    """ATT&CK ships Mobile M1013 as a verbatim copy of Enterprise M1013."""
    mobile = read_library(MOBILE)

    own_ref_ids = {
        control["ref_id"] for control in mobile["objects"]["reference_controls"]
    }
    assert "M1013" not in own_ref_ids

    assert f"urn:intuitem:risk:library:{ENTERPRISE}" in mobile.get("dependencies", [])

    enterprise_urn = f"urn:intuitem:risk:function:{ENTERPRISE}:m1013"
    borrowing = [
        technique["ref_id"]
        for technique in mobile["objects"]["techniques"]
        if enterprise_urn in (technique.get("reference_controls") or [])
    ]
    assert borrowing, "no Mobile technique links the Enterprise M1013"

    # loading Mobile alone must pull Enterprise in through that dependency
    load_library(MOBILE)
    assert ReferenceControl.objects.filter(urn=enterprise_urn).exists()
    for ref_id in borrowing:
        technique = Technique.objects.get(
            urn=f"urn:intuitem:risk:technique:{MOBILE}:{ref_id.lower()}"
        )
        assert technique.reference_controls.filter(urn=enterprise_urn).exists()


@pytest.mark.django_db
@pytest.mark.parametrize("ref_id", [ICS, MOBILE])
def test_placeholder_mitigations_are_not_reference_controls(ref_id):
    """ "Mitigation Limited or Not Effective" and "Do Not Mitigate" are not controls."""
    library = read_library(ref_id)
    names = {control["name"] for control in library["objects"]["reference_controls"]}
    assert "Mitigation Limited or Not Effective" not in names
    assert "Do Not Mitigate" not in names

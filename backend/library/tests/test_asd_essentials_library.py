"""Regression tests for the ASD Essentials for enterprise IT library.

Generated by `tools/build_asd_essentials.py` from ASD's OSCAL release. The
principle counts per domain are the totals of the example summary table in
ASD's Essentials assessment process guide.
"""

import collections
from pathlib import Path

import pytest
import yaml
from core.models import Framework, LoadedLibrary, RequirementNode, StoredLibrary

LIBRARIES_DIR = Path(__file__).resolve().parents[2] / "library" / "libraries"

REF_ID = "asd-essentials-enterprise-it"
MAPPING = f"mapping-essential-eight-2023-and-{REF_ID}"

PRINCIPLES_PER_DOMAIN = {
    "Governance and culture": 7,
    "Visibility and response": 10,
    "Boundary services": 16,
    "Identity services": 16,
    "Critical processes and services": 16,
    "Privileged environments": 16,
    "Business systems": 13,
    "User devices": 10,
}
FIRST_PHASE = {
    "Governance and culture",
    "Visibility and response",
    "Boundary services",
    "Identity services",
}


def load(ref_id):
    urn = f"urn:intuitem:risk:library:{ref_id}"
    if not LoadedLibrary.objects.filter(urn=urn).exists():
        stored = StoredLibrary.objects.filter(urn=urn).first()
        if stored is None:
            content = (LIBRARIES_DIR / f"{ref_id}.yaml").read_bytes()
            stored, error = StoredLibrary.store_library_content(content)
            assert error is None, f"could not store {ref_id}: {error}"
        assert stored.load() is None


@pytest.fixture
def framework(db) -> Framework:
    load(REF_ID)
    return Framework.objects.get(urn=f"urn:intuitem:risk:framework:{REF_ID}")


@pytest.mark.django_db
class TestAsdEssentialsLibrary:
    def test_domains_hold_the_principles_asd_counts(self, framework):
        nodes = RequirementNode.objects.filter(framework=framework)
        domains = {n.urn: n.name for n in nodes.filter(parent_urn__isnull=True)}
        counts = collections.Counter(
            domains[n.parent_urn] for n in nodes if n.parent_urn in domains
        )
        assert counts == PRINCIPLES_PER_DOMAIN

    def test_actions_are_rated_once_per_domain(self, framework):
        actions = RequirementNode.objects.filter(framework=framework, assessable=True)
        assert actions.count() == 212
        assert len(set(actions.values_list("ref_id", flat=True))) == 58
        assert all(a.annotation for a in actions)

    def test_a_phase_includes_earlier_phases_and_capability_domains(self, framework):
        domains = RequirementNode.objects.filter(
            framework=framework, parent_urn__isnull=True
        )
        in_phase_1 = {d.name for d in domains if "1" in d.implementation_groups}
        assert in_phase_1 == FIRST_PHASE
        assert all("3" in d.implementation_groups for d in domains)

    def test_transition_mapping_links_existing_requirements(self, framework):
        load("essential-eight-2023")
        content = yaml.safe_load((LIBRARIES_DIR / f"{MAPPING}.yaml").read_text())
        rows = content["objects"]["requirement_mapping_set"]["requirement_mappings"]
        sources = {r["source_requirement_urn"] for r in rows}
        targets = {r["target_requirement_urn"] for r in rows}
        known = set(
            RequirementNode.objects.filter(urn__in=sources | targets).values_list(
                "urn", flat=True
            )
        )
        assert sources | targets <= known
        assert len(targets) > 100

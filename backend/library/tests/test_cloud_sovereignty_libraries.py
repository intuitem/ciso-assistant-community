"""Regression tests for the EU CADA proposal and Cloud Sovereignty Framework (June 2026) libraries.

Generated by `tools/build_eu_cada_proposal.py` (Annexes II and III of COM(2026) 502) and
`tools/build_cloud_sovereignty_framework_2026.py` (the Commission's sovereignty calculator).
"""

import re
from pathlib import Path

import pytest
import yaml

from core.models import ComplianceAssessment, Framework, RequirementNode, StoredLibrary

LIBRARIES_DIR = Path(__file__).resolve().parents[2] / "library" / "libraries"


def _nodes(name):
    text = (LIBRARIES_DIR / f"{name}.yaml").read_text(encoding="utf-8")
    return yaml.safe_load(text)["objects"]["framework"]["requirement_nodes"]


@pytest.mark.parametrize(
    "name", ["eu-cada-proposal", "cloud-sovereignty-framework-2026"]
)
def test_libraries_have_no_yaml_aliases(name):
    text = (LIBRARIES_DIR / f"{name}.yaml").read_text(encoding="utf-8")
    assert not re.search(r"[&*]id\d+", text)


def _visible(nodes, group):
    """Same rule as ComplianceAssessment.requirement_matches_selected_groups."""
    audit = ComplianceAssessment(selected_implementation_groups=[group])
    return {
        n["ref_id"]
        for n in nodes
        if audit.requirement_matches_selected_groups(
            RequirementNode(implementation_groups=n.get("implementation_groups"))
        )
    }


@pytest.mark.django_db
@pytest.mark.parametrize("level", [1, 2, 3, 4])
def test_cada_levels_include_lower_level_criteria(level):
    # Article 20(1): a higher-level audit must meet every lower-level criterion
    nodes = _nodes("eu-cada-proposal")
    visible = _visible(nodes, f"UAL-{level}")
    for lower in range(1, level + 1):
        assert {
            n["ref_id"] for n in nodes if n["ref_id"].startswith(f"{lower}.1(")
        } <= visible
    assert not any(
        r.startswith(f"{higher}.") for r in visible for higher in range(level + 1, 5)
    )
    assert "Annex II" in visible


@pytest.mark.django_db
def test_cada_ual2_audit_shows_subcontractor_oversight():
    assert "1.1(f)" in _visible(_nodes("eu-cada-proposal"), "UAL-2")


def test_cada_third_country_control_is_assessable_with_article_note():
    node = next(n for n in _nodes("eu-cada-proposal") if n["ref_id"] == "3.1(g)")
    assert node["assessable"] is True
    assert "Article 18" in node["annotation"]


def test_cada_evidence_carries_annex_iii_strictness_note():
    with_evidence = [n for n in _nodes("eu-cada-proposal") if n.get("typical_evidence")]
    assert with_evidence and all(n["ref_id"][0] in "234" for n in with_evidence)
    assert all(
        "depending on the assurance level criteria" in n["typical_evidence"]
        for n in with_evidence
    )


def test_seal_2026_matches_official_weights_and_question_counts():
    nodes = _nodes("cloud-sovereignty-framework-2026")
    assert {n["ref_id"]: (n["weight"], len(n["questions"])) for n in nodes} == {
        "SOV-1": (20, 8), "SOV-2": (10, 6), "SOV-3": (10, 5), "SOV-4": (15, 6),
        "SOV-5": (10, 7), "SOV-6": (15, 5), "SOV-7": (15, 7), "SOV-8": (5, 4),
    }  # fmt: skip
    for n in nodes:
        for q in n["questions"].values():
            scores = [c["add_score"] for c in q["choices"]]
            assert min(scores) == 0 and max(scores) == 100
            no_impact = ["(no SEAL impact)" in c["value"] for c in q["choices"]]
            assert all(no_impact) or not any(no_impact)


@pytest.mark.django_db
@pytest.mark.parametrize(
    "name, nodes, assessable",
    [("eu-cada-proposal", 69, 52), ("cloud-sovereignty-framework-2026", 8, 8)],
)
def test_libraries_load(name, nodes, assessable):
    stored = StoredLibrary.objects.get(urn=f"urn:intuitem:risk:library:{name}")
    assert stored.load() is None
    framework = Framework.objects.get(urn=f"urn:intuitem:risk:framework:{name}")
    loaded = RequirementNode.objects.filter(framework=framework)
    assert loaded.count() == nodes
    assert loaded.filter(assessable=True).count() == assessable

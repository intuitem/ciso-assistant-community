"""Regression tests for the MonServiceSécurisé V2 framing quick form.

Generated by `tools/build_mss_framing_form.py`. The outcomes must give what MSS
gives on the same description: minimum security needs (`niveauSecuriteRequis`),
the risks retained (`configurationSelectionVecteurs`) and the target objectives
(`configurationSelectionObjectifsVises`). Expected values are worked by hand from
those MSS tables.
"""

from pathlib import Path

import pytest
import yaml

from core.cel_service import (
    evaluate_quick_form_document,
    validate_quick_form_expressions,
)
from core.models import LoadedLibrary, QuickForm, StoredLibrary

REF_ID = "quick-form-anssi-mss-v2-framing"
PATH = Path(__file__).resolve().parents[2] / "library" / "libraries" / f"{REF_ID}.yaml"
PAGE = "urn:intuitem:risk:qf_page:anssi-mss-v2-framing"


@pytest.fixture(scope="module")
def form() -> dict:
    return yaml.safe_load(PATH.read_text(encoding="utf-8"))["objects"]["quick_forms"][0]


def answers(**chosen) -> dict:
    """chosen: page__question=choice or [choices]."""
    out = {}
    for key, value in chosen.items():
        page, question = key.split("__")
        urn = f"{PAGE}:{page}:question:{question}"
        out[urn] = (
            [f"{urn}:choice:{v}" for v in value]
            if isinstance(value, list)
            else f"{urn}:choice:{value}"
        )
    return out


def fired(form, **chosen) -> set[str]:
    return set(
        evaluate_quick_form_document(form, answers(**chosen))["computed_outcome"]
    )


def by_prefix(outcomes: set[str], prefix: str) -> set[str]:
    return {o.removeprefix(prefix) for o in outcomes if o.startswith(prefix)}


def test_every_expression_evaluates(form):
    assert validate_quick_form_expressions(form) == []


def evaluate(form, **chosen) -> dict:
    return evaluate_quick_form_document(form, answers(**chosen))["computed_outcome"]


def needs_value(form, **chosen) -> float | None:
    result = evaluate_quick_form_document(form, answers(**chosen))
    return result["computed_values"].get("besoins_securite")


def test_exposed_saas_with_sensitive_data(form):
    computed = evaluate(
        form,
        perimetre__hebergement="saas",
        usages__ouverture="accessibleSurInternet",
        usages__audience="large",
        usages__duree="moinsDe4h",
        donnees__volumetrie="eleve",
        donnees__categories=["donneesSensibles"],
    )
    outcomes = set(computed)
    # données: high volume x criticité 4 -> 4; disponibilité: large x <4h -> 4;
    # exposition: internet -> 3; besoins[4][3] = niveau3 (Avancés).
    assert by_prefix(outcomes, "besoins_") == {"niveau3"}
    assert (
        needs_value(
            form,
            usages__ouverture="accessibleSurInternet",
            usages__audience="large",
            usages__duree="moinsDe4h",
            donnees__volumetrie="eleve",
            donnees__categories=["donneesSensibles"],
        )
        == 3.0
    )
    assert computed["besoins_niveau3"]["audit_implementation_groups"] == ["A-I", "A-R"]
    assert computed["besoins_niveau3"]["framework"].endswith(":framework:anssi-mss-v2")
    # SaaS adds V3 V7 V9 V11 V14 and removes V2 V6 V13; internet adds V4 and V12,
    # which only needs at niveau1 would remove; V5 is always there.
    assert by_prefix(outcomes, "risque_r") == {
        "3",
        "4",
        "5",
        "7",
        "9",
        "11",
        "12",
        "14",
    }
    assert by_prefix(outcomes, "objectif_") == {"ov2", "ov3"}


def test_severity_follows_the_selected_objectives(form):
    values = evaluate_quick_form_document(
        form,
        answers(
            donnees__volumetrie="eleve",
            usages__duree="moinsDe4h",
            usages__audience="tresLarge",
        ),
    )["computed_values"]
    # No service type selected: OV1 and OV4 are not in play, so the audience does
    # not count. OV2 = high volume (3), OV3 = under 4h (4).
    assert values["gravite_ov1"] == 0.0
    assert values["gravite_ov2"] == 3.0
    assert values["gravite_ov3"] == 4.0
    assert values["gravite_r4"] == 4.0  # OV1-OV4: the highest selected
    assert values["gravite_r5"] == 3.0  # OV2 only


def test_internal_service_with_basic_needs(form):
    computed = evaluate(
        form,
        perimetre__hebergement="onPremise",
        usages__ouverture="interneRestreint",
        usages__audience="limitee",
        usages__duree="plusDe24h",
        donnees__volumetrie="faible",
    )
    outcomes = set(computed)
    assert by_prefix(outcomes, "besoins_") == {"niveau1"}
    assert computed["besoins_niveau1"]["audit_implementation_groups"] == ["B-I", "B-R"]
    # Defaults V2 V5 V6 V13; needs at niveau1 remove V2.
    assert by_prefix(outcomes, "risque_r") == {"5", "6", "13"}


def test_selections_follow_service_type_and_specificities(form):
    outcomes = fired(
        form,
        perimetre__type_service=["serviceEnLigne"],
        perimetre__specificites=["echangeOuReceptionEmails", "postesDeTravail"],
    )
    assert by_prefix(outcomes, "objectif_") == {"ov1", "ov2", "ov3", "ov4"}
    assert "risque_r1" in outcomes


def test_needs_wait_for_the_answers_they_read(form):
    assert not by_prefix(fired(form, usages__audience="large"), "besoins_")
    assert needs_value(form, usages__audience="large") == 0.0


@pytest.mark.django_db
def test_library_stores_and_loads():
    urn = f"urn:intuitem:risk:library:{REF_ID}"
    stored = StoredLibrary.objects.filter(urn=urn).first()
    if stored is None:
        stored, error = StoredLibrary.store_library_content(PATH.read_bytes())
        assert error is None, error
    assert stored.load() is None
    assert LoadedLibrary.objects.filter(urn=urn).exists()
    quick_form = QuickForm.objects.get(
        urn="urn:intuitem:risk:quick_form:anssi-mss-v2-framing"
    )
    assert quick_form.subject_question_urn.endswith(":service:question:service")

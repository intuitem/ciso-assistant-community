"""Regression tests for the MonServiceSécurisé V2 measures library.

Generated by `tools/build_mss_referentiel.py`. The ref_ids are the ids the MSS
public API returns, and the implementation groups mirror the MSS rules engine.
"""

from collections import Counter
from pathlib import Path

import pytest
from core.models import Framework, LoadedLibrary, StoredLibrary, Threat

LIBRARIES_DIR = Path(__file__).resolve().parents[2] / "library" / "libraries"

REF_ID = "anssi-mss-v2"
MAPPING_REF_ID = f"mapping-{REF_ID}-and-recyf"
FRAMEWORK_URN = f"urn:intuitem:risk:framework:{REF_ID}"


def load(ref_id: str) -> None:
    urn = f"urn:intuitem:risk:library:{ref_id}"
    if LoadedLibrary.objects.filter(urn=urn).exists():
        return
    stored = StoredLibrary.objects.filter(urn=urn).first()
    if stored is None:
        content = (LIBRARIES_DIR / f"{ref_id}.yaml").read_bytes()
        stored, error = StoredLibrary.store_library_content(content)
        assert error is None, f"could not store {ref_id}: {error}"
    assert stored.load() is None


@pytest.fixture
def framework(db) -> Framework:
    load(REF_ID)
    return Framework.objects.get(urn=FRAMEWORK_URN)


@pytest.mark.django_db
class TestAnssiMssV2Library:
    def test_six_themes_and_135_measures(self, framework):
        nodes = framework.requirement_nodes.all()
        assert nodes.filter(parent_urn__isnull=True, assessable=False).count() == 6
        assert nodes.filter(parent_urn__isnull=False, assessable=True).count() == 135

    def test_measures_keep_the_mss_api_ids(self, framework):
        node = framework.requirement_nodes.get(ref_id="ADMIN.1")
        assert node.urn == f"urn:intuitem:risk:req_node:{REF_ID}:admin.1"

    def test_groups_follow_the_rules_engine(self, framework):
        counts = Counter(
            group
            for groups in framework.requirement_nodes.values_list(
                "implementation_groups", flat=True
            )
            for group in groups or []
        )
        assert counts == {
            "B-I": 35,
            "B-R": 23,
            "M-I": 68,
            "M-R": 19,
            "A-I": 105,
            "A-R": 19,
        }

    def test_measures_suggest_key_reference_controls(self, framework):
        node = framework.requirement_nodes.get(ref_id="COMPADMIN.4")
        assert [rc.ref_id for rc in node.reference_controls.all()] == [
            "DOC.PAM_REGISTER"
        ]

    def test_gaps_use_the_controls_added_for_mss(self, framework):
        node = framework.requirement_nodes.get(ref_id="FILTRE.4")
        assert [rc.ref_id for rc in node.reference_controls.all()] == [
            "TECH.DDOS_PROTECTION"
        ]

    def test_risk_vectors_are_threats_of_the_measures_that_lower_them(self, framework):
        threats = Threat.objects.filter(
            library__urn=f"urn:intuitem:risk:library:{REF_ID}"
        )
        assert threats.count() == 14
        assert threats.get(ref_id="MSS-V4").name == (
            "Compromission d'un service ou d'un serveur exposé"
        )
        # MSS reads MCO_MCS.7 for the likelihood of these 8 vectors.
        node = framework.requirement_nodes.get(ref_id="MCO_MCS.7")
        assert {t.ref_id for t in node.threats.all()} == {
            f"MSS-V{n}" for n in (1, 2, 3, 4, 8, 9, 13, 14)
        }
        nodes = framework.requirement_nodes.filter(assessable=True)
        assert nodes.filter(threats__isnull=False).distinct().count() == 95

    def test_audit_computes_mss_likelihood(self, framework):
        from core.cel_service import evaluate_outcomes
        from core.models import ComplianceAssessment
        from iam.models import Folder

        audit = ComplianceAssessment.objects.create(
            name="mss",
            framework=framework,
            folder=Folder.get_root_folder(),
            selected_implementation_groups=["B-I", "B-R"],
        )
        audit.create_requirement_assessments()

        def likelihood(compliant: list[str]) -> float:
            audit.requirement_assessments.update(result="not_assessed")
            audit.requirement_assessments.filter(
                requirement__ref_id__in=compliant
            ).update(result="compliant")
            evaluate_outcomes(audit)
            audit.refresh_from_db()
            return audit.computed_values["vraisemblance_v4"]

        # V4 at Basique: 4 - 2 x all of (MCO_MCS.15, .5, .6, DEV.1) + 1 x none of AUDIT.6
        group_a = ["MCO_MCS.15", "MCO_MCS.5", "MCO_MCS.6", "DEV.1"]
        assert likelihood([]) == 4.0  # 5, bounded
        assert likelihood(group_a) == 3.0
        assert likelihood(group_a + ["AUDIT.6"]) == 2.0
        rule = next(
            r
            for r in framework.outcomes_definition
            if r["ref_id"] == "vraisemblance_v4"
        )
        assert rule["likelihood_of"].endswith(":threat:anssi-mss-v2:v4")

    def test_recyf_mapping_loads(self, framework):
        load(MAPPING_REF_ID)

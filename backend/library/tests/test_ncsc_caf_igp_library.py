"""Regression tests for the NCSC CAF 4.0 IGP questionnaire library.

The library is generated by `tools/excel/ncsc/tools/ncsc-caf_v4_igp_builder.py`
from the published CAF 4.0 PDF. These tests pin what a regeneration must not
break: the shape of the questionnaire, and the verdict its answers produce.

The framework runs on `tiered_all` aggregation, so the indicator answers alone
decide the outcome status, exactly as the tables print it:

    Not Achieved       at least one of the following statements is true
    Partially Achieved all the following statements are true
    Achieved           all the following statements are true
"""

import collections
import re
from pathlib import Path

import pytest
from core.models import (
    Answer,
    ComplianceAssessment,
    Framework,
    LoadedLibrary,
    Perimeter,
    Question,
    RequirementAssessment,
    RequirementNode,
    StoredLibrary,
)
from iam.models import Folder

LIBRARIES_DIR = Path(__file__).resolve().parents[2] / "library" / "libraries"

REF_ID = "ncsc-caf-4.0-igp"
LIBRARY_URN = f"urn:intuitem:risk:library:{REF_ID}"
FRAMEWORK_URN = f"urn:intuitem:risk:framework:{REF_ID}"
GROUPED_REF_ID = "ncsc-caf-4.0-igp-grouped"
GROUPED_LIBRARY_URN = f"urn:intuitem:risk:library:{GROUPED_REF_ID}"
GROUPED_FRAMEWORK_URN = f"urn:intuitem:risk:framework:{GROUPED_REF_ID}"

EXPECTED_OBJECTIVES = 4
EXPECTED_PRINCIPLES = 14
EXPECTED_OUTCOMES = 41
# 184 Not Achieved + 148 Partially Achieved + 225 Achieved statements.
EXPECTED_STATEMENTS = {"NA": 184, "PA": 148, "A": 225}
# A4.b is the one table whose page break puts a Partially Achieved continuation
# at the Not Achieved x-position. Pinned verbatim from the PDF: a regression
# here means the builder has gone back to filing that fragment by geometry,
# which truncates one statement and corrupts another.
A4B_PAGE_BREAK = {
    "A4.b.NA.4": (
        "Vulnerabilities are discovered in software despite the negligible "
        "difficulty of implementing mitigations."
    ),
    "A4.b.PA.3": (
        "You consider the security of environments (e.g. development, test and "
        "production), including source code and repositories, used in the "
        "production of software to be appropriate and proportionate within the "
        "context of common threats."
    ),
    "A4.b.PA.4": (
        "The testing regime uses a range of different approaches (e.g. static "
        "and dynamic analysis, unit and integration testing and point in time "
        "assessments) that verify all aspects of the development lifecycle "
        "covering both functional and non-functional testing."
    ),
}
# What a True answer states, per column, and what a False answer states.
EXPECTED_TIERS = {
    "NA": ["non_compliant", None],
    "PA": ["partially_compliant", None],
    "A": ["compliant", "non_compliant"],
}
# Outcomes whose IGP table has no Partially Achieved column.
TWO_STATE_OUTCOMES = {
    "A1.a",
    "A1.b",
    "A1.c",
    "A2.c",
    "A3.a",
    "D1.b",
    "D1.c",
    "D2.a",
    "D2.b",
}

STATEMENT_RE = re.compile(r"^\[([A-D]\d+\.[a-z])\.(NA|PA|A)\.(\d+)\]")


@pytest.fixture
def framework(db) -> Framework:
    # The shipped libraries are already in the test database; only store the
    # file when running against a database that predates it.
    if not LoadedLibrary.objects.filter(urn=LIBRARY_URN).exists():
        stored = StoredLibrary.objects.filter(urn=LIBRARY_URN).first()
        if stored is None:
            content = (LIBRARIES_DIR / f"{REF_ID}.yaml").read_bytes()
            stored, error = StoredLibrary.store_library_content(content)
            assert error is None, f"could not store {REF_ID}: {error}"
        assert stored.load() is None
    return Framework.objects.get(urn=FRAMEWORK_URN)


@pytest.fixture
def grouped_framework(db) -> Framework:
    if not LoadedLibrary.objects.filter(urn=GROUPED_LIBRARY_URN).exists():
        stored = StoredLibrary.objects.filter(urn=GROUPED_LIBRARY_URN).first()
        if stored is None:
            content = (LIBRARIES_DIR / f"{GROUPED_REF_ID}.yaml").read_bytes()
            stored, error = StoredLibrary.store_library_content(content)
            assert error is None, f"could not store {GROUPED_REF_ID}: {error}"
        assert stored.load() is None
    return Framework.objects.get(urn=GROUPED_FRAMEWORK_URN)


def outcome(framework: Framework, ref_id: str) -> RequirementNode:
    return RequirementNode.objects.get(framework=framework, ref_id=ref_id)


def column_of(question: Question) -> str:
    match = STATEMENT_RE.match(question.text)
    assert match, f"unindexed question: {question.text}"
    return match.group(2)


@pytest.mark.django_db
class TestLibraryShape:
    def test_tree_is_the_caf_outcome_tree(self, framework):
        nodes = list(RequirementNode.objects.filter(framework=framework))
        assert len(nodes) == (
            EXPECTED_OBJECTIVES + EXPECTED_PRINCIPLES + EXPECTED_OUTCOMES
        )

        levels = collections.Counter()
        for node in nodes:
            for level, pattern in (
                ("objective", r"^[A-D]$"),
                ("principle", r"^[A-D]\d+$"),
                ("outcome", r"^[A-D]\d+\.[a-z]$"),
            ):
                if re.match(pattern, node.ref_id):
                    levels[level] += 1
                    break
            else:
                pytest.fail(f"unexpected node {node.ref_id}")

        assert levels["objective"] == EXPECTED_OBJECTIVES
        assert levels["principle"] == EXPECTED_PRINCIPLES
        assert levels["outcome"] == EXPECTED_OUTCOMES

        # The contributing outcome is the unit of assessment, nothing below it.
        assessable = [node for node in nodes if node.assessable]
        assert len(assessable) == EXPECTED_OUTCOMES
        assert all(re.match(r"^[A-D]\d+\.[a-z]$", node.ref_id) for node in assessable)
        outcome_urns = {node.urn for node in assessable}
        assert not [node for node in nodes if node.parent_urn in outcome_urns]

    def test_the_answers_decide_the_result(self, framework):
        assert framework.result_aggregation == Framework.ResultAggregation.TIERED_ALL, (
            "without tiered_all the indicator answers cannot produce the CAF verdict"
        )

    def test_every_indicator_is_a_true_false_question_stating_its_tier(self, framework):
        questions = Question.objects.filter(
            requirement_node__framework=framework
        ).prefetch_related("choices")
        assert questions.count() == sum(EXPECTED_STATEMENTS.values())

        counts = collections.Counter()
        for question in questions:
            assert question.type == Question.Type.UNIQUE_CHOICE
            column = column_of(question)
            counts[column] += 1
            choices = list(question.choices.order_by("order"))
            assert [choice.value for choice in choices] == ["True", "False"]
            assert [choice.compute_result for choice in choices] == EXPECTED_TIERS[
                column
            ], question.text

        assert dict(counts) == EXPECTED_STATEMENTS

    def test_every_outcome_carries_its_own_indicators(self, framework):
        for node in RequirementNode.objects.filter(
            framework=framework, assessable=True
        ).prefetch_related("questions"):
            columns = collections.Counter(
                column_of(question) for question in node.questions.all()
            )
            assert columns["A"], f"{node.ref_id} has no Achieved statements"
            if node.ref_id in TWO_STATE_OUTCOMES:
                assert not columns["PA"], f"{node.ref_id} should have no PA column"
            else:
                assert columns["PA"], f"{node.ref_id} should have a PA column"

    def test_irrelevant_dimensions_are_hidden_by_default(self, framework):
        """The CAF has no numeric scale and no certification vocabulary, so new
        audits should not offer scoring or nonconformity fields, and the
        outcome status is the verdict rather than a workflow state."""
        assert framework.field_visibility == {
            field: {"auditor": "hidden", "respondent": "hidden"}
            for field in ("score", "documentation_score", "extended_result", "status")
        }
        # What the assessment is actually made of stays on the page.
        for field in ("answers", "result", "observation", "evidences"):
            assert field not in framework.field_visibility

    def test_progress_follows_the_result(self, framework):
        """Hiding `status` is what moves an audit off status-driven progress,
        so an outcome counts as assessed once its answers produce a verdict."""
        status_driven, result_visible = (
            ComplianceAssessment.progress_mode_from_visibility(
                None, framework.field_visibility
            )
        )
        assert not status_driven
        assert result_visible

    def test_the_a4b_page_break_statements_are_whole(self, framework):
        texts = {}
        for question in Question.objects.filter(
            requirement_node__framework=framework,
            requirement_node__ref_id="A4.b",
        ):
            match = STATEMENT_RE.match(question.text)
            texts[f"{match.group(1)}.{match.group(2)}.{match.group(3)}"] = (
                question.text[match.end() :].strip()
            )

        for ref_id, expected in A4B_PAGE_BREAK.items():
            assert texts.get(ref_id) == expected, ref_id

    def test_statements_are_indexed_the_way_the_caf_indexes_them(self, framework):
        node = outcome(framework, "A2.a")
        prefixes = [
            q.text.split("]")[0] + "]" for q in node.questions.order_by("order")
        ]
        assert prefixes[0] == "[A2.a.NA.1]"
        assert "[A2.a.PA.1]" in prefixes
        assert "[A2.a.A.1]" in prefixes


@pytest.mark.django_db
class TestGroupedLibraryShape:
    def test_groups_cover_every_question_once_in_caf_column_order(
        self, grouped_framework
    ):
        nodes = RequirementNode.objects.filter(
            framework=grouped_framework, assessable=True
        ).prefetch_related("questions")
        assert nodes.count() == EXPECTED_OUTCOMES

        for node in nodes:
            groups = node.questions_properties.get("groups")
            assert isinstance(groups, dict), node.ref_id
            ordered_groups = [groups[key] for key in sorted(groups, key=int)]
            expected_descriptions = (
                ["Not Achieved", "Achieved"]
                if node.ref_id in TWO_STATE_OUTCOMES
                else ["Not Achieved", "Partially Achieved", "Achieved"]
            )
            assert [group["description"] for group in ordered_groups] == (
                expected_descriptions
            )

            questions = list(node.questions.order_by("order"))
            questions_by_urn = {question.urn: question for question in questions}
            grouped_urns = [
                question_urn
                for group in ordered_groups
                for question_urn in group["order"]
            ]
            assert grouped_urns == [question.urn for question in questions]
            assert len(grouped_urns) == len(set(grouped_urns))

            expected_columns = ["NA", "A"]
            if node.ref_id not in TWO_STATE_OUTCOMES:
                expected_columns.insert(1, "PA")
            for group, expected_column in zip(ordered_groups, expected_columns):
                assert {
                    column_of(questions_by_urn[question_urn])
                    for question_urn in group["order"]
                } == {expected_column}

    def test_grouping_does_not_change_the_calculation_rule(self, grouped_framework):
        assert (
            grouped_framework.result_aggregation
            == Framework.ResultAggregation.TIERED_ALL
        )


@pytest.mark.django_db
class TestResultFollowsTheIndicators:
    @pytest.fixture
    def assessment(self, framework):
        folder = Folder.get_root_folder()
        perimeter = Perimeter.objects.create(name="CAF IGP", folder=folder)
        ca = ComplianceAssessment.objects.create(
            name="CAF IGP audit",
            framework=framework,
            folder=folder,
            perimeter=perimeter,
        )
        ca.create_requirement_assessments()
        return ca

    def answer_outcome(self, ca, ref_id, *, false=(), true_na=(), skip=()):
        """Answer a whole outcome as a well-run organisation would: no Not
        Achieved statement true, every Partially achieved and Achieved one
        true. `false` / `true_na` flip named statements ("A.2", "PA.1", ...),
        `skip` leaves one unanswered.
        """
        node = outcome(ca.framework, ref_id)
        ra = RequirementAssessment.objects.get(
            compliance_assessment=ca, requirement=node
        )
        for question in node.questions.order_by("order"):
            match = STATEMENT_RE.match(question.text)
            name = f"{match.group(2)}.{match.group(3)}"
            if name in skip:
                continue
            column = match.group(2)
            if column == "NA":
                value = name in true_na
            else:
                value = name not in false
            choice = question.choices.order_by("order")[0 if value else 1]
            row, _ = Answer.objects.get_or_create(
                requirement_assessment=ra,
                question=question,
                defaults={"folder": ra.folder},
            )
            row.selected_choices.set([choice])

        ra.compute_score_and_result()
        ra.refresh_from_db()
        return ra

    def test_all_achieved_statements_true_is_achieved(self, assessment):
        ra = self.answer_outcome(assessment, "A2.a")
        assert ra.result == RequirementAssessment.Result.COMPLIANT

    def test_falls_back_to_partially_achieved(self, assessment):
        ra = self.answer_outcome(assessment, "A2.a", false={"A.1"})
        assert ra.result == RequirementAssessment.Result.PARTIALLY_COMPLIANT

    def test_not_achieved_when_the_partial_tier_breaks_too(self, assessment):
        ra = self.answer_outcome(assessment, "A2.a", false={"A.1", "PA.2"})
        assert ra.result == RequirementAssessment.Result.NON_COMPLIANT

    def test_a_not_achieved_statement_overrides_everything(self, assessment):
        """The contradiction a manual status dropdown could not catch."""
        ra = self.answer_outcome(assessment, "A2.a", true_na={"NA.3"})
        assert ra.result == RequirementAssessment.Result.NON_COMPLIANT

    def test_two_state_outcome_cannot_be_partially_achieved(self, assessment):
        """A1.a has no Partially Achieved column, so one missed statement means
        Not achieved. Worst-wins aggregation would have said partially."""
        assert self.answer_outcome(assessment, "A1.a").result == (
            RequirementAssessment.Result.COMPLIANT
        )
        ra = self.answer_outcome(assessment, "A1.a", false={"A.4"})
        assert ra.result == RequirementAssessment.Result.NON_COMPLIANT

    def test_result_waits_for_every_indicator(self, assessment):
        ra = self.answer_outcome(assessment, "A1.a", skip={"NA.2"})
        assert ra.result == RequirementAssessment.Result.NOT_ASSESSED
